"""Check Python syntax before starting or restarting a worker.

Usage: python validated_restart.py /path/to/source [command ...]

The command runs in the source directory. Without a command, a demo worker
simply sleeps. Keep virtual environments outside the watched source tree.
"""

from __future__ import annotations

import logging
import py_compile
import re
import subprocess
import sys
import threading
import time
from pathlib import Path
from tempfile import TemporaryDirectory

from watchdog.events import FileSystemEvent, PatternMatchingEventHandler
from watchdog.observers import Observer

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)


class ValidatedRestartHandler(PatternMatchingEventHandler):
    def __init__(self, directory: Path, command: list[str]) -> None:
        super().__init__(patterns=["**/*.py"], ignore_directories=True, case_sensitive=True)
        self.directory = directory
        self.command = command
        self.changed = threading.Event()
        self.process: subprocess.Popen[bytes] | None = None

    def on_any_event(self, event: FileSystemEvent) -> None:
        # Reading sources during validation must not trigger another restart.
        if event.event_type in {"created", "modified", "deleted", "moved"}:
            self.changed.set()

    def restart_if_valid(self) -> None:
        # Clear before checking so changes during validation remain pending.
        self.changed.clear()
        try:
            # Keep generated bytecode outside the source tree.
            with TemporaryDirectory() as cache_directory:
                for index, source in enumerate(self.directory.rglob("*.py")):
                    py_compile.compile(
                        str(source),
                        cfile=str(Path(cache_directory) / f"{index}.pyc"),
                        doraise=True,
                    )
        except (py_compile.PyCompileError, OSError) as exc:
            logger.warning("Validation failed; restart skipped: %s", exc)
            return

        if self.changed.is_set():
            return

        # Check the entry point for the direct "python worker.py [args ...]" form.
        if (
            len(self.command) > 1
            and Path(self.command[1]).suffix == ".py"
            and (
                self.command[0] == sys.executable
                or re.fullmatch(r"(?:pythonw?|pypy)(?:\d+(?:\.\d+)*)?(?:\.exe)?", Path(self.command[0]).name.lower())
            )
        ):
            entrypoint = self.directory / self.command[1]
            if not entrypoint.is_file():
                logger.warning("Worker entry point missing; restart skipped: %s", entrypoint)
                return

        self.stop_process()
        logger.info("Validation passed; starting worker: %s", self.command)
        self.process = subprocess.Popen(self.command, cwd=self.directory)

    def stop_process(self) -> None:
        if self.process is None:
            return
        if self.process.poll() is None:
            self.process.terminate()
        try:
            self.process.wait(timeout=5)
        except subprocess.TimeoutExpired:
            self.process.kill()
            self.process.wait()
        except KeyboardInterrupt:
            self.process.kill()
            self.process.wait()
            self.process = None
            raise
        self.process = None


directory = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
command = sys.argv[2:] or [
    sys.executable,
    "-u",
    "-c",
    "import time; print('Demo worker running'); time.sleep(3600)",
]

event_handler = ValidatedRestartHandler(directory, command)
observer = Observer()
observer.schedule(event_handler, str(directory), recursive=True)
observer.start()
try:
    event_handler.restart_if_valid()
    while True:
        time.sleep(0.5)
        # Only the main thread validates and manages the worker process.
        if event_handler.changed.is_set():
            event_handler.restart_if_valid()
finally:
    observer.stop()
    observer.join()
    event_handler.stop_process()
